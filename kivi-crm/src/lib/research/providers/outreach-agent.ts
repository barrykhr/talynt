import "server-only";
import { z } from "zod";
import { ResearchError, type ResearchInput } from "../schema";
import type { ProviderOutput, ResearchProvider } from "./types";

// Adapter for the EXISTING standalone outreach agent's HTTP API
// (POST {OUTREACH_AGENT_URL}/api/generate, Basic auth with APP_PASSWORD).
// Its response lists research points and sources separately, so claims can't
// be tied to a source: they are stored as low-confidence inferences and the
// consulted sources are listed as a warning. Prefer the built-in providers.
const agentResponse = z.object({
  role: z.string().optional(),
  company: z.string().optional(),
  researchPoints: z.array(z.string()).default([]),
  sources: z.array(z.string()).default([]),
  message: z.string().default(""),
});

function baseUrl() {
  const raw = process.env.OUTREACH_AGENT_URL?.trim();
  if (!raw) return null;
  try {
    const u = new URL(raw);
    return u.protocol === "https:" || u.hostname === "localhost" || u.hostname === "127.0.0.1" ? u.toString().replace(/\/$/, "") : null;
  } catch {
    return null;
  }
}

async function call(input: ResearchInput, signal: AbortSignal): Promise<ProviderOutput> {
  const url = baseUrl();
  if (!url) throw new ResearchError("OUTREACH_AGENT_URL is not configured.", false);
  const headers: Record<string, string> = { "Content-Type": "application/json" };
  if (process.env.OUTREACH_AGENT_PASSWORD) {
    headers.Authorization = `Basic ${Buffer.from(`crm:${process.env.OUTREACH_AGENT_PASSWORD}`).toString("base64")}`;
  }
  let res: Response;
  try {
    res = await fetch(`${url}/api/generate`, {
      method: "POST",
      headers,
      signal,
      body: JSON.stringify({
        level: input.level,
        role: input.role ?? "",
        location: input.location ?? "",
        companyName: input.company.name,
        linkedinUrl: input.company.linkedinUrl ?? "",
        notes: [input.company.website ? `Website: ${input.company.website}` : "", input.crmContext ?? ""].filter(Boolean).join("\n"),
        personName: input.contact?.name ?? "",
        personTitle: input.contact?.title ?? "",
        personNotes: input.contact?.notes ?? "",
        senderName: input.sender.name,
      }),
    });
  } catch {
    throw new ResearchError("The outreach agent is not reachable at OUTREACH_AGENT_URL.", true);
  }
  if (res.status === 401) throw new ResearchError("The outreach agent rejected the password (OUTREACH_AGENT_PASSWORD).", false);
  if (res.status === 400) {
    const body = (await res.json().catch(() => ({}))) as { error?: string };
    throw new ResearchError(`The outreach agent rejected the input: ${String(body.error ?? "bad request").slice(0, 200)}`, false);
  }
  if (!res.ok) throw new ResearchError(`The outreach agent returned HTTP ${res.status}.`, true);
  const parsed = agentResponse.safeParse(await res.json().catch(() => null));
  if (!parsed.success) throw new ResearchError("The outreach agent returned an unexpected response.", true);
  const a = parsed.data;
  return {
    model: "outreach-agent",
    retrieved: null,
    raw: {
      about_brief: null,
      industry: null,
      employee_range: null,
      outreach_angle: null,
      draft_subject: null,
      draft_message: a.message || null,
      warnings: a.sources.length ? [`Sources the agent consulted (not linked to specific claims): ${a.sources.slice(0, 8).join(", ")}`.slice(0, 300)] : [],
      findings: a.researchPoints.slice(0, 10).map((p) => ({
        category: "other" as const,
        statement: p.slice(0, 1000),
        evidence_kind: "inference" as const,
        confidence: "low" as const,
        source_url: null,
        source_title: null,
        published_on: null,
        excerpt: null,
        conflict_note: "Returned by the outreach agent without a per-claim source. Verify before relying on it.",
      })),
    },
    extraWarnings: ["Generated by the standalone outreach agent, which does not attribute sources per claim."],
  };
}

export const outreachAgentProvider: ResearchProvider = {
  id: "outreach-agent",
  label: "Existing outreach agent (HTTP)",
  configured: () => Boolean(baseUrl()),
  missingConfig: () => (baseUrl() ? [] : ["OUTREACH_AGENT_URL"]),
  supportsDraftOnly: false,
  research: call,
  draft: call,
};
